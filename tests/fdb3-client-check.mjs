import assert from 'node:assert/strict';
import {KitchenStore} from '../web/fdb3-store.js';
const memory = new Map();
const storage = {getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,value)};
const first = new KitchenStore(storage);
const request = (command,args={},request_id=crypto.randomUUID().replaceAll('-','')) => ({command,args,request_id,session_id:first.sessionId,input_token:first.inputToken});
const original = request('add_checklist_item',{text:'Rinse the basil'});
const a = first.execute(original); assert.equal(a.status,'success');
assert.equal(first.read().items.length,1);
assert.deepEqual(first.execute(original),a,'Retry returns durable receipt without repeating the effect');
assert.equal(first.read().items.length,1);
assert.equal(first.execute({...original,args:{text:'Boil water'}}).status,'error','A request ID cannot acquire different arguments');
const stale = request('add_checklist_item',{text:'This should not be saved'});
first.newInput(); assert.equal(first.execute(stale).status,'error'); assert.equal(first.read().items.length,1);
for(const command of ['cleanup','set_input','request_timer_handoff','delete_everything']) assert.equal(first.execute(request(command)).status,'error');
assert.equal(first.execute(request('set_checklist_item',{item_id:a.item_id,checked:'true'})).status,'error');
assert.equal(first.execute(request('set_checklist_item',{item_id:a.item_id,checked:true})).status,'success');
assert.match(first.execute(request('read_checklist')).detail,/Checked: Rinse the basil/,'Readback names the actual saved item and checked state');
const second = new KitchenStore(storage);
assert.equal(second.sessionId,first.sessionId); assert.equal(second.read().items[0].checked,true,'New client retains real saved state');
assert.equal(first.execute(request('add_checklist_item',{text:'Old tab'})).status,'error','A second tab revokes admission for the old tab');
const foreign={command:'read_checklist',args:{},request_id:crypto.randomUUID().replaceAll('-',''),session_id:'1'.repeat(32),input_token:second.inputToken};
assert.equal(second.execute(foreign).status,'error');
const previous=structuredClone(second.read());
storage.setItem=()=>{throw Error('Quota exceeded');};
const failed=second.execute({...foreign,session_id:second.sessionId,command:'add_checklist_item',args:{text:'No false completion'}});
assert.equal(failed.error,'outcome_unknown'); assert.deepEqual(second.read(),previous);
const corrupt={getItem:()=>'{broken',setItem:()=>assert.fail('Corrupted saved state must not be replaced')};
assert.throws(()=>new KitchenStore(corrupt));
console.log(JSON.stringify({suite:'FDB-v3 browser admission and persistence',passed:true,assertions:21}));
